#!/usr/bin/env python3
"""Audit original per-level status artwork; input binaries are never committed.

python3 tests/status_icon_source_audit.py --source-dir <local extracted zipbin> \
  --write-sql migrations/000000_init-57.sql --write-audit <local audit.json>
The native ov_res schema, not a guessed resource/skill relationship, defines offsets.
"""
import argparse, hashlib, json, struct
from pathlib import Path

SCHEMA_SHA256 = 'c232005d56717e2e255e1e927dde709b243e34b7599e00c45d67f0760c5e270f'
DESC_SHA256 = 'caccc5a2f58687240d811458d895499a2dddf2ddeed10d5f383a928117bb3119'

def read_source(root):
    schema = (root / 'ov_res.bin').read_bytes()
    data = (root / 'ov_exceptdesc.bin').read_bytes()
    assert hashlib.sha256(schema).hexdigest() == SCHEMA_SHA256, 'different original schema'
    assert hashlib.sha256(data).hexdigest() == DESC_SHA256, 'different original status table'
    # A field descriptor is 88 bytes immediately before its 64-byte name slot.
    for name, position, layout in [('Desc', 242296, (256, 0, 256, 1)),
                                  ('Name', 242448, (32, 256, 32, 1)),
                                  ('SmallMap', 242600, (4, 288, 1, 4)),
                                  ('Type', 244968, (4, 0, 1, 4)),
                                  ('levels', 245120, (12320, 4, 40, 308))]:
        assert schema[position:position+64].split(b'\0')[0].decode() == name
        descriptor = struct.unpack_from('<22i', schema, position-88)
        assert descriptor[6:10] == layout, (name, descriptor)
    assert struct.unpack_from('<4I', data) == (0x5566, 1, 12324, 206)
    assert len(data) == 16+12324*206
    rows = []
    for row_no in range(206):
        start = 16+row_no*12324
        status = struct.unpack_from('<I', data, start)[0]
        levels = []
        for index in range(40):
            offset = start+4+index*308
            block = data[offset:offset+308]
            levels.append(dict(level=index+1,
                name=block[256:288].split(b'\0')[0].decode('gbk'),
                icon=struct.unpack_from('<I', block, 288)[0],
                byte_offset=offset+288))
        rows.append(dict(row_no=row_no, status_id=status, levels=levels))
    return rows

def sql(rows):
    values = ',\n'.join('      (%d, %d, ARRAY[%s])' % (r['row_no'], r['status_id'],
                      ','.join(str(x['icon']) for x in r['levels'])) for r in rows)
    return f'''-- Restore the original ResExceptDesc.SmallMap omitted by the initial importer.
-- Generated by tests/status_icon_source_audit.py; no binary artwork is included.
-- ov_res.bin sha256: {SCHEMA_SHA256}
-- ov_exceptdesc.bin sha256: {DESC_SHA256}
-- Original schema: 206 physical rows; Type u32 + 40 levels of 308 bytes;
-- each level has Desc[256], Name[32], SmallMap u32 at +288.
-- This is also the idempotent incremental patch for existing databases.
-- Apply this fragment inside a transaction BEFORE starting the new server.
-- Only native static status presentation metadata is changed; no player data.
ALTER TABLE gamedata.ov_exceptdesc
  ADD COLUMN IF NOT EXISTS level_small_maps integer[];
COMMENT ON COLUMN gamedata.ov_exceptdesc.level_small_maps IS
  'Original ResExceptDesc.SmallMap for all 40 levels; PostgreSQL index is the 1-based status level. Zero is authored, not missing metadata.';
DO $status_icons$
DECLARE updated_rows integer;
BEGIN
  WITH recovered(row_no, status_id, icons) AS (VALUES
{values}
  )
  UPDATE gamedata.ov_exceptdesc d SET level_small_maps = r.icons
    FROM recovered r WHERE d.row_no = r.row_no AND d.type = r.status_id;
  GET DIAGNOSTICS updated_rows = ROW_COUNT;
  IF updated_rows <> 206 THEN
    RAISE EXCEPTION 'Original status icon row mismatch: updated %, expected 206', updated_rows;
  END IF;
END
$status_icons$;
'''

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--source-dir', type=Path, required=True)
    ap.add_argument('--write-sql', type=Path);ap.add_argument('--verify-sql', type=Path)
    ap.add_argument('--write-audit', type=Path);args=ap.parse_args();rows=read_source(args.source_dir)
    positive=[r for r in rows if r['status_id']>0]
    payload=dict(source_schema_sha256=SCHEMA_SHA256, source_table_sha256=DESC_SHA256,
                 physical_rows=len(rows), unique_positive_statuses=len(positive), rows=rows)
    if args.write_sql:args.write_sql.write_text(sql(rows))
    if args.verify_sql:assert args.verify_sql.read_text()==sql(rows), 'SQL differs from original source'
    if args.write_audit:args.write_audit.write_text(json.dumps(payload,ensure_ascii=False,indent=2)+'\n')
    print('PASS original schema and all %d levels; %d positive status IDs; %d have positive original artwork' %
          (len(rows)*40,len(positive),sum(any(x['icon']>0 for x in r['levels'])for r in positive)))
if __name__=='__main__':main()
