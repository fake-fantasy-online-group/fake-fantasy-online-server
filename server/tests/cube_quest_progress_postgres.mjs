// PGLITE_MODULE=/path/to/@electric-sql/pglite node server/tests/cube_quest_progress_postgres.mjs
import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {PGlite}=require(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const db=new PGlite();
const migration=fs.readFileSync(new URL('../migrations/000000_init-85.sql',import.meta.url),'utf8');
await db.exec(`
CREATE TABLE characters(id bigint primary key, trial_daily_completed integer not null default 0, trial_cycle integer not null default 0);
CREATE TABLE character_quests(char_id bigint, task_id integer, state integer, progress integer, primary key(char_id,task_id));
CREATE TABLE game_trial_rules(quest_id integer);
CREATE TABLE endgame_runs(run_id text primary key, state text, payload jsonb);
INSERT INTO game_trial_rules VALUES(99);
INSERT INTO characters(id) SELECT generate_series(1,13);
UPDATE characters SET trial_daily_completed=1 WHERE id=2;
UPDATE characters SET trial_cycle=1 WHERE id=3;
INSERT INTO character_quests VALUES(4,99,2,0),(5,99,0,0),(6,99,0,0);
`);
const completion=(id,version=2,claimed=false)=>({Version:version,Kind:'trial',Nonce:String(id),Keys:{[id]:1},Grants:version>=2?{[id]:{Claimed:claimed}}:undefined});
const add=async(id,payload,state='trial.completed')=>db.query('INSERT INTO endgame_runs VALUES($1,$2,$3::jsonb)',[`trial-${id}`,state,JSON.stringify(payload)]);
await add(6,completion(6));
await add(7,{...completion(7),Grants:{}});
await add(8,completion(8,1));
await add(9,completion(9),'trial.active');
await add(10,{...completion(10),Kind:'rift'});
await add(11,{...completion(11),Keys:{11:0}});
await add(12,completion(12,2,true));
await add(13,{...completion(13),Keys:{13:'not-a-number'}});
await db.exec(migration);
const qualified=async()=> (await db.query('SELECT id FROM characters WHERE trial_completed_once ORDER BY id')).rows.map(r=>Number(r.id));
assert.deepEqual(await qualified(),[2,3,4,6,8,12]);
await db.exec(migration);
assert.deepEqual(await qualified(),[2,3,4,6,8,12]);
// Clearing/resetting daily repeatable state cannot revoke the migrated proof.
await db.exec('UPDATE characters SET trial_daily_completed=0,trial_cycle=0; DELETE FROM character_quests; DELETE FROM endgame_runs;');
await db.exec(migration);
assert.deepEqual(await qualified(),[2,3,4,6,8,12]);
const inventory=fs.readFileSync(new URL('../internal/store/inventory.go',import.meta.url),'utf8');
const select=inventory.match(/`(SELECT task_id, state, progress, accepted_at_ms, rift_completion_run_id FROM character_quests WHERE char_id = \$1)`/)[1];
const columns=inventory.match(/\[\]string\{("char_id", "task_id", "state", "progress", "accepted_at_ms", "rift_completion_run_id")\}/)[1].split(', ').map(x=>JSON.parse(x));
await db.query(`INSERT INTO character_quests(${columns.join(',')}) VALUES($1,$2,$3,$4,$5,$6)`,[6,1900030001,0,0,1720000000000,'complete-run']);
assert.deepEqual((await db.query(select,[6])).rows,[{task_id:1900030001,state:0,progress:0,accepted_at_ms:1720000000000,rift_completion_run_id:'complete-run'}]);
await assert.rejects(db.query('UPDATE character_quests SET accepted_at_ms=-1'));
await assert.rejects(db.query('UPDATE character_quests SET rift_completion_run_id=$1',['x'.repeat(65)]));
const postgres=fs.readFileSync(new URL('../internal/store/postgres.go',import.meta.url),'utf8');
assert.ok(postgres.includes('trial_completed_once=trial_completed_once OR $61'));
await db.query('UPDATE characters SET trial_completed_once=trial_completed_once OR $1 WHERE id=6',[false]);
assert.equal((await db.query('SELECT trial_completed_once FROM characters WHERE id=6')).rows[0].trial_completed_once,true);
console.log('PASS migration85: proven legacy trial qualifications only, idempotent permanent backfill, acceptance/run marker production query and save columns, invalid event markers rejected, permanent qualification cannot be revoked.');
await db.close();
