// Shared typed building blocks for the 2026-11 buff pass. Every helper keeps
// the generated status owned by the wearing power (LegendaryPowerID and
// LegendarySourceUID) so unequip/expiry cleanup and presentation stay exact.

// bpOwnShieldActive reports whether the wearer still carries an unbroken
// shield generated by this power instance.
func bpOwnShieldActive(c *legendaryContext) bool {
	found := false
	if c != nil && c.Owner != nil && c.Owner.Status != nil {
		c.Owner.Status.EachEffective(func(a domain.Active) {
			if a.ShieldLeft > 0 && a.Def.LegendaryPowerID == c.Power.ID && (a.Def.LegendarySourceUID == 0 || a.Def.LegendarySourceUID == c.SourceUID) {
				found = true
			}
		})
	}
	return found
}

// bpLanded is a landed direct hit by the wearer on a hostile target.
func bpLanded(c *legendaryContext) bool {
	return c != nil && c.Owner != nil && c.Target != nil && c.Owner.ID != c.Target.ID && !sameParty(c.Owner, c.Target) && legendaryMeleeLanded(c)
}

// bpLifesteal heals the wearer by pct% of the HP its landed direct hit
// actually removed (overkill and shield absorption excluded).
func bpLifesteal(c *legendaryContext, pct int32) {
	if pct <= 0 || !bpLanded(c) || c.LostHP <= 0 || !c.Owner.Alive() {
		return
	}
	amount := clampI32(int64(c.LostHP) * int64(pct) / 100)
	if amount <= 0 {
		return
	}
	c.RestoreHealth(c.Owner, amount, c.Skill)
}

// bpHealPctMax restores pct% of the target's maximum HP.
func bpHealPctMax(c *legendaryContext, target *entity.Entity, pctX10 int64) {
	if c == nil || target == nil || !target.Alive() || target.MaxHP <= 0 || pctX10 <= 0 {
		return
	}
	amount := clampI32(int64(target.MaxHP) * pctX10 / 1000)
	if amount > 0 {
		c.RestoreHealth(target, amount, 0)
	}
}

// bpRegenTick restores pctX10/10 % maximum HP once per second while active.
// The state carries no expiry, so it lives exactly as long as the power is worn.
func bpRegenTick(c *legendaryContext, phase string, pctX10 int64, active bool) {
	if c == nil || c.Preview || c.Owner == nil {
		return
	}
	st := c.State(0, phase)
	if !active || !c.Owner.Alive() {
		st.NextMS = 0
		return
	}
	if st.NextMS == 0 {
		st.NextMS = c.NowMS + 1000
		return
	}
	if c.NowMS < st.NextMS {
		return
	}
	st.NextMS = c.NowMS + 1000
	bpHealPctMax(c, c.Owner, pctX10)
}

// bpMaxHP scales maximum HP by pct%.
func bpMaxHP(st *domain.Stats, pct int32) {
	if st != nil {
		st.MaxHP = specialScale(st.MaxHP, 100+pct)
	}
}

func bpStatusDef(c *legendaryContext, phase string, durationSec int32) domain.StatusDef {
	def := domain.StatusDef{
		ID: legendaryMeleeStatusID(c, phase), Level: 1, Name: c.Power.Name, Desc: c.Power.Effect,
		Icon: legendaryMeleeIcon(c), IconKnown: true, TypeKnown: true, Type: domain.StatusGood,
		EffectHitBP: 100000000, LegendaryPowerID: c.Power.ID, LegendarySourceUID: c.SourceUID,
	}
	if durationSec > 0 {
		def.DurationSec = durationSec
	} else {
		def.Permanent = true
	}
	return def
}

func bpReplaceStatus(c *legendaryContext, target *entity.Entity, def domain.StatusDef) bool {
	if c == nil || c.Preview || target == nil || !target.Alive() {
		return false
	}
	if target.Status != nil {
		c.Scene.statusesRemoved(target, target.Status.RemoveWhere(func(d domain.StatusDef) bool { return d.ID == def.ID }))
	}
	return c.Scene.applyStatusDef(target, def, c.Owner.ID)
}

// bpShield grants a pct% max-HP shield; the stronger of the old and new
// remaining amounts is kept. durationSec<=0 keeps it until broken.
func bpShield(c *legendaryContext, target *entity.Entity, phase string, pct int32, durationSec int32) bool {
	if bpShieldQuiet(c, target, phase, pct, durationSec) {
		c.Visual("stage-01", target)
		return true
	}
	return false
}

// bpShieldQuiet is bpShield without the hit cue.
func bpShieldQuiet(c *legendaryContext, target *entity.Entity, phase string, pct int32, durationSec int32) bool {
	if c == nil || target == nil || !target.Alive() || target.MaxHP <= 0 || pct <= 0 {
		return false
	}
	def := bpStatusDef(c, phase, durationSec)
	amount := specialScale(target.MaxHP, pct)
	if target.Status != nil {
		target.Status.EachEffective(func(a domain.Active) {
			if a.Def.ID == def.ID {
				amount = max(amount, a.ShieldLeft)
			}
		})
	}
	def.DamageShield = amount
	return bpReplaceStatus(c, target, def)
}

// bpTimed applies a refreshed timed status owned by this power.
func bpTimed(c *legendaryContext, target *entity.Entity, phase string, durationSec int32, harmful bool, edit func(*domain.StatusDef)) bool {
	if c == nil || target == nil || durationSec <= 0 {
		return false
	}
	def := bpStatusDef(c, phase, durationSec)
	if harmful {
		def.Type = domain.StatusBad
	}
	if edit != nil {
		edit(&def)
	}
	return bpReplaceStatus(c, target, def)
}

// bpVulnerable marks a hostile target so it takes more damage from everyone.
func bpVulnerable(c *legendaryContext, target *entity.Entity, physical, magic, durationSec int32) bool {
	if c == nil || target == nil || !target.Alive() || target.ID == c.Owner.ID || sameParty(c.Owner, target) {
		return false
	}
	return bpTimed(c, target, "vulnerable", durationSec, true, func(d *domain.StatusDef) {
		d.PhysicalDamageTakenPct = physical
		d.MagicDamageTakenPct = magic
	})
}

// bpAllies returns living party members (wearer included) within radius.
func bpAllies(c *legendaryContext, center domain.Pos, radius float64, includeSelf bool) []*entity.Entity {
	if c == nil || c.Owner == nil {
		return nil
	}
	var out []*entity.Entity
	for _, e := range c.Scene.partyMembersInScene(c.Owner) {
		if e == nil || !e.Alive() || (!includeSelf && e.ID == c.Owner.ID) || e.Pos.MapID != center.MapID {
			continue
		}
		if sqDist(center, e.Pos) <= radius*radius {
			out = append(out, e)
		}
	}
	return out
}

// bpHostilesInRange lists living hostile entities around center.
func bpHostilesInRange(c *legendaryContext, center domain.Pos, radius float64) []*entity.Entity {
	if c == nil {
		return nil
	}
	return c.Enemies(center, radius, len(c.Scene.entities))
}

// bpPullToward drags a pullable hostile toward center, stopping at stop.
func bpPullToward(c *legendaryContext, target *entity.Entity, center domain.Pos, stop float64) {
	if target == nil || !target.Alive() || target.Pos.MapID != center.MapID {
		return
	}
	distance := math.Sqrt(sqDist(center, target.Pos))
	if distance <= stop {
		return
	}
	legendaryCasterPull(c, target, center, distance-stop)
}

// bpLandedTargets returns distinct enemies landed by the wearer in this root.
func bpLandedTargets(c *legendaryContext) []domain.EntityID {
	seen := map[domain.EntityID]bool{}
	var out []domain.EntityID
	for _, h := range c.Hits {
		if h.src != c.Owner.ID || h.ev.Flag.Has(event.DamageMiss) || seen[h.dst] {
			continue
		}
		if t := c.Scene.entities[h.dst]; t == nil || t.ID == c.Owner.ID || sameParty(c.Owner, t) {
			continue
		}
		seen[h.dst] = true
		out = append(out, h.dst)
	}
	return out
}

// bpOwnerHPBelow reports HP strictly below pct% of maximum.
func bpOwnerHPBelow(c *legendaryContext, pct int64) bool {
	return c.Owner != nil && c.Owner.MaxHP > 0 && int64(c.Owner.HP)*100 < int64(c.Owner.MaxHP)*pct
}

