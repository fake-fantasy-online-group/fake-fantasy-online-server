-- 1.5.8 货架回收。客户端展示 30 天/80%，服务端以购买流水和仍持有的
-- 可消耗数量为准；客户端回传的价格、每份数量和份数只作为行指纹复核。
CREATE TABLE IF NOT EXISTS game_rack_refund_rule (
    singleton   BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    refund_pct  SMALLINT NOT NULL DEFAULT 80 CHECK (refund_pct BETWEEN 1 AND 100),
    window_days SMALLINT NOT NULL DEFAULT 30 CHECK (window_days BETWEEN 1 AND 365),
    used_ok     BOOLEAN NOT NULL DEFAULT TRUE
);
INSERT INTO game_rack_refund_rule(singleton) VALUES(TRUE)
ON CONFLICT(singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS game_rack_purchases (
    id              BIGSERIAL PRIMARY KEY,
    char_id         BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    item_id         INT NOT NULL CHECK (item_id > 0),
    unit_price      INT NOT NULL CHECK (unit_price > 0),
    bundle          INT NOT NULL CHECK (bundle > 0),
    shares          INT NOT NULL CHECK (shares > 0),
    refunded_shares INT NOT NULL DEFAULT 0 CHECK (refunded_shares BETWEEN 0 AND shares),
    purchased_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rack_purchases_refund
    ON game_rack_purchases(char_id,purchased_at,item_id)
    WHERE refunded_shares < shares;

CREATE TABLE IF NOT EXISTS game_deposit_rule (
    singleton      BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    auto_credit    BOOLEAN NOT NULL DEFAULT TRUE,
    caiyu_per_unit BIGINT NOT NULL DEFAULT 100 CHECK (caiyu_per_unit > 0),
    max_amount     INT NOT NULL DEFAULT 100000 CHECK (max_amount > 0)
);
INSERT INTO game_deposit_rule(singleton) VALUES(TRUE) ON CONFLICT(singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS game_deposit_requests (
    id         BIGSERIAL PRIMARY KEY,
    char_id    BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    chain      TEXT NOT NULL CHECK (char_length(chain) BETWEEN 1 AND 40),
    amount     INT NOT NULL CHECK (amount > 0),
    caiyu      BIGINT NOT NULL CHECK (caiyu > 0),
    status     TEXT NOT NULL DEFAULT 'credited' CHECK (status IN ('pending','credited','rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_deposit_requests_char ON game_deposit_requests(char_id,created_at DESC);

-- 宠物魂之精货架。商品号按 90000000 + pet_id 生成；仅上架非野外可捕捉的宠物。
CREATE TABLE IF NOT EXISTS game_rack_pet_goods (
    item_id INT PRIMARY KEY REFERENCES game_rack_goods(item_id),
    pet_id INT NOT NULL UNIQUE REFERENCES game_pets(id)
);

WITH pets AS (
    SELECT DISTINCT ON (pet_id) pet_id,capture_level,starve_add1
      FROM gamedata.ov_petgrow WHERE pet_id > 0 ORDER BY pet_id,row_no
)
INSERT INTO game_rack_goods(item_id,category_id,price,quantity,flags,remain,part,active)
SELECT 90000000+pet_id,7,1,1,0,-1,'',TRUE FROM pets
 WHERE capture_level=0 AND starve_add1<>0
ON CONFLICT(item_id) DO UPDATE SET category_id=EXCLUDED.category_id,price=EXCLUDED.price,
    quantity=EXCLUDED.quantity,flags=EXCLUDED.flags,remain=EXCLUDED.remain,
    part=EXCLUDED.part,active=EXCLUDED.active;

WITH pets AS (
    SELECT DISTINCT ON (pet_id) pet_id,capture_level,starve_add1
      FROM gamedata.ov_petgrow WHERE pet_id > 0 ORDER BY pet_id,row_no
)
INSERT INTO game_rack_pet_goods(item_id,pet_id)
SELECT 90000000+pet_id,pet_id FROM pets WHERE capture_level=0 AND starve_add1<>0
ON CONFLICT(item_id) DO UPDATE SET pet_id=EXCLUDED.pet_id;

