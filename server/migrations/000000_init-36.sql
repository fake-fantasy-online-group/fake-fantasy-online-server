-- 家族基础状态。等级、成员上限、职位与权限继续以 gamedata.ov_fam* 为配置事实源；
-- 这里只保存玩家实际创建出来的家族、成员关系及自定义职位名。

CREATE TABLE IF NOT EXISTS game_families (
    id             BIGSERIAL PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 30),
    proclaim       TEXT NOT NULL DEFAULT '' CHECK (char_length(proclaim) <= 500),
    level          SMALLINT NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 7),
    reputation     BIGINT NOT NULL DEFAULT 0 CHECK (reputation >= 0),
    wealth         BIGINT NOT NULL DEFAULT 0 CHECK (wealth >= 0),
    resist         BOOLEAN NOT NULL DEFAULT FALSE,
    leader_char_id BIGINT NOT NULL UNIQUE REFERENCES characters(id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS game_family_members (
    family_id    BIGINT NOT NULL REFERENCES game_families(id) ON DELETE CASCADE,
    char_id      BIGINT NOT NULL UNIQUE REFERENCES characters(id) ON DELETE CASCADE,
    position_id  SMALLINT NOT NULL DEFAULT 10 CHECK (position_id BETWEEN 1 AND 10),
    contribution BIGINT NOT NULL DEFAULT 0 CHECK (contribution >= 0),
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (family_id, char_id)
);
CREATE INDEX IF NOT EXISTS idx_family_members_family ON game_family_members(family_id, position_id, joined_at);

CREATE TABLE IF NOT EXISTS game_family_position_names (
    family_id   BIGINT NOT NULL REFERENCES game_families(id) ON DELETE CASCADE,
    position_id SMALLINT NOT NULL CHECK (position_id BETWEEN 3 AND 9),
    name        TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 20),
    PRIMARY KEY (family_id, position_id)
);

CREATE TABLE IF NOT EXISTS game_family_stash_settings (
    family_id     BIGINT PRIMARY KEY REFERENCES game_families(id) ON DELETE CASCADE,
    take_position SMALLINT NOT NULL DEFAULT 2 CHECK (take_position BETWEEN 1 AND 10)
);

CREATE TABLE IF NOT EXISTS game_family_stash_items (
    family_id              BIGINT NOT NULL REFERENCES game_families(id) ON DELETE CASCADE,
    stash_index            INT NOT NULL CHECK (stash_index >= 0),
    uid                    BIGINT NOT NULL DEFAULT 0,
    item_id                INT NOT NULL CHECK (item_id > 0),
    count                  INT NOT NULL CHECK (count > 0),
    durability             INT NOT NULL DEFAULT 0,
    max_durability         INT NOT NULL DEFAULT 0 CHECK (max_durability >= 0),
    durability_wear_raw    INT NOT NULL DEFAULT 0 CHECK (durability_wear_raw BETWEEN 0 AND 299),
    bound                  BOOLEAN NOT NULL DEFAULT FALSE,
    locked                 BOOLEAN NOT NULL DEFAULT FALSE,
    refine_level           INT NOT NULL DEFAULT 0 CHECK (refine_level >= 0),
    socket_count           SMALLINT NOT NULL DEFAULT 0 CHECK (socket_count BETWEEN 0 AND 5),
    sockets                INT[] NOT NULL DEFAULT ARRAY[0,0,0,0,0] CHECK (cardinality(sockets)=5),
    wash_quality           SMALLINT NOT NULL DEFAULT 0 CHECK (wash_quality BETWEEN 0 AND 4),
    wash_count             SMALLINT NOT NULL DEFAULT 0 CHECK (wash_count BETWEEN 0 AND 4),
    wash_attrs             INT[] NOT NULL DEFAULT ARRAY[0,0,0,0] CHECK (cardinality(wash_attrs)=4),
    wash_values            INT[] NOT NULL DEFAULT ARRAY[0,0,0,0] CHECK (cardinality(wash_values)=4),
    wash_modes             INT[] NOT NULL DEFAULT ARRAY[0,0,0,0] CHECK (cardinality(wash_modes)=4),
    fused_appearance_item_id INT NOT NULL DEFAULT 0 CHECK (fused_appearance_item_id >= 0),
    deposited_by           TEXT NOT NULL CHECK (char_length(deposited_by) BETWEEN 1 AND 30),
    deposited_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (family_id,stash_index)
);

