 IF EXISTS(SELECT FROM game_rack_goods g WHERE g.category_id=0
     AND NOT EXISTS(SELECT FROM rack_restore_parts x WHERE x.item_id=g.item_id)) THEN
  RAISE EXCEPTION 'rack restore unaudited costume';
 END IF;
 UPDATE game_rack_goods g SET active=false FROM rack_restore_remove x WHERE g.item_id=x.item_id;
 -- All shop listings for ring spirits, including a nonstandard category or hidden
 -- promotion and shared NPC stock. Only stock rows are removed, never definitions.
 UPDATE game_rack_goods g SET active=false WHERE EXISTS(
   SELECT FROM game_items i WHERE i.id=g.item_id AND i.name LIKE '%戒灵%'
   UNION ALL SELECT FROM game_equipment e WHERE e.id=g.item_id AND e.name LIKE '%戒灵%');
 -- NPC shop loader requires contiguous zero-based slots. Rebuild only affected
 -- stock lists, in their previous order, rather than leaving holes after removal.
 CREATE TEMP TABLE rack_restore_npc_shops ON COMMIT DROP AS
 SELECT DISTINCT s.shop_id FROM game_shop_items s WHERE EXISTS(
   SELECT FROM game_items i WHERE i.id=s.item_id AND i.name LIKE '%戒灵%'
   UNION ALL SELECT FROM game_equipment e WHERE e.id=s.item_id AND e.name LIKE '%戒灵%');
 CREATE TEMP TABLE rack_restore_npc_stock ON COMMIT DROP AS
 SELECT s.shop_id,(row_number() OVER(PARTITION BY s.shop_id ORDER BY s.slot)-1)::int AS slot,s.item_id
 FROM game_shop_items s JOIN rack_restore_npc_shops affected USING(shop_id)
 WHERE NOT EXISTS(
   SELECT FROM game_items i WHERE i.id=s.item_id AND i.name LIKE '%戒灵%'
   UNION ALL SELECT FROM game_equipment e WHERE e.id=s.item_id AND e.name LIKE '%戒灵%');
 DELETE FROM game_shop_items s USING rack_restore_npc_shops affected WHERE s.shop_id=affected.shop_id;
 INSERT INTO game_shop_items(shop_id,slot,item_id) SELECT shop_id,slot,item_id FROM rack_restore_npc_stock;
 -- Do not reactivate retired goods or change quantity, purchase history, flags/currency.
 UPDATE game_rack_goods g SET price=x.tier*10 FROM rack_restore_prices x
 WHERE g.item_id=x.item_id AND g.active;
 UPDATE game_rack_goods g SET category_id=x.category_id,part=x.part FROM rack_restore_parts x
 WHERE g.item_id=x.item_id;
END $rack_restore$;
COMMIT;
