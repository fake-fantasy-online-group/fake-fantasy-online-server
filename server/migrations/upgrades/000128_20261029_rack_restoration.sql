   gamedata.ov_petgrow,gamedata.ov_avatararm,game_pet_profiles,game_item_saddle_pets IN SHARE MODE;
 -- Reject identity drift before touching listings; already inactive is replay-safe.
 SELECT count(*) INTO n FROM rack_restore_remove x
 JOIN game_rack_goods g ON g.item_id=x.item_id
 LEFT JOIN game_rack_pet_goods p ON p.item_id=x.item_id
 LEFT JOIN game_items i ON i.id=x.item_id
 LEFT JOIN game_equipment e ON e.id=x.item_id
 LEFT JOIN LATERAL (SELECT name FROM gamedata.ov_petgrow
     WHERE pet_id=p.pet_id ORDER BY row_no LIMIT 1) pet ON true
 WHERE CASE WHEN p.pet_id IS NOT NULL THEN p.pet_id=x.pet_id AND pet.name||'魂之精'=x.expected_name
     ELSE COALESCE(i.name,e.name)=x.expected_name AND (x.pet_id=0 OR EXISTS(
       SELECT FROM game_item_pet_eggs egg WHERE egg.item_id=x.item_id AND egg.pet_id=x.pet_id)) END;
 IF n<>442 THEN RAISE EXCEPTION 'rack restore removal identity drift: %/442',n; END IF;
 -- The list is reviewed, but do not remove a pet that became naturally rideable
 -- since that review. Missing-profile pets use the same native initial skills as
 -- LoadPets; profile-backed pets use the complete initial/forbidden skill lists.
 IF EXISTS(SELECT FROM rack_restore_remove x
   LEFT JOIN game_pet_profiles profile ON profile.pet_id=x.pet_id
   JOIN LATERAL (SELECT * FROM gamedata.ov_petgrow WHERE pet_id=x.pet_id ORDER BY row_no LIMIT 1) p ON true
   WHERE x.reason='saddle_required_pet' AND
    (NOT EXISTS(SELECT FROM game_item_saddle_pets saddle WHERE saddle.pet_id=x.pet_id)
     OR (p.horse_base_spd>0 AND
       ((profile.pet_id IS NOT NULL AND ('坐骑'=ANY(profile.initial_skill_names)
         OR NOT ('坐骑'=ANY(profile.forbidden_skill_names))))
        OR (profile.pet_id IS NULL AND 13002=ANY(ARRAY[p.init_skills1_id,p.init_skills2_id,
          p.init_skills3_id,p.init_skills4_id,p.init_skills5_id,p.init_skills6_id])))))) THEN
  RAISE EXCEPTION 'rack restore saddle requirement drift';
 END IF;
 SELECT count(*) INTO n FROM rack_restore_prices x
 JOIN game_rack_goods g ON g.item_id=x.item_id
 JOIN game_rack_pet_goods p ON p.item_id=x.item_id AND p.pet_id=x.pet_id
 JOIN LATERAL (SELECT name,pet_circle FROM gamedata.ov_petgrow
     WHERE pet_id=p.pet_id ORDER BY row_no LIMIT 1) pet ON true
 WHERE pet.name=x.expected_name AND pet.pet_circle=x.tier AND x.tier BETWEEN 1 AND 5 AND (g.flags & 4)=0;
 IF n<>180 THEN RAISE EXCEPTION 'rack restore pet tier identity drift: %/180',n; END IF;
 SELECT count(*) INTO n FROM rack_restore_parts x
 JOIN game_rack_goods g ON g.item_id=x.item_id
 JOIN game_items i ON i.id=x.item_id AND i.name=x.expected_name
 WHERE (x.item_id=10626 AND x.slot=0 AND x.category_id=4 AND x.part='')
