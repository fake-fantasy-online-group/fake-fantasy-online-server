#!/usr/bin/env bash
# Private, pinned Go SDK and module caches; no system install or server startup.
set -euo pipefail
ROOT="${1:-${FFO_SERVER_TOOLCHAIN_HOME:-$HOME/.cache/ffo/server-toolchains}}"
VERSION=1.27.2
SHA256=ecbadb99091a3f46e31f5f934b068b1864eafa7995211b39eaddf76996045fe5
for tool in curl sha256sum tar; do command -v "$tool" >/dev/null || { echo "Missing prerequisite: $tool" >&2; exit 1; }; done
[[ "$(uname -s)/$(uname -m)" == Linux/x86_64 ]] || { echo 'This locked bootstrap targets Linux x86_64.' >&2; exit 1; }
mkdir -p "$ROOT/downloads"; ROOT="$(cd "$ROOT" && pwd)"
ARCHIVE="$ROOT/downloads/go$VERSION.linux-amd64.tar.gz"
if [[ ! -f "$ARCHIVE" ]]; then
 curl --fail --location --silent --show-error --max-time 180 "https://go.dev/dl/go$VERSION.linux-amd64.tar.gz" -o "$ARCHIVE.partial"
 printf '%s  %s\n' "$SHA256" "$ARCHIVE.partial" | sha256sum -c -
 mv "$ARCHIVE.partial" "$ARCHIVE"
fi
printf '%s  %s\n' "$SHA256" "$ARCHIVE" | sha256sum -c -
if [[ ! -x "$ROOT/go/bin/go" ]]; then
 tar -xzf "$ARCHIVE" -C "$ROOT"
elif [[ "$("$ROOT/go/bin/go" version)" != "go version go$VERSION linux/amd64" ]]; then
 echo "Existing Go SDK differs from pinned version. Choose a fresh toolchain directory." >&2
 exit 1
fi
{
 printf '# Generated by bootstrap-go-test-toolchain.sh; source this file in Bash.\n'
 printf 'export FFO_SERVER_TOOLCHAIN_HOME=%q\n' "$ROOT"
 cat <<'ENV'
export GOROOT="$FFO_SERVER_TOOLCHAIN_HOME/go"
export GOPATH="$FFO_SERVER_TOOLCHAIN_HOME/gopath"
export GOMODCACHE="$GOPATH/pkg/mod"
export GOCACHE="$FFO_SERVER_TOOLCHAIN_HOME/gocache"
export GOTOOLCHAIN=local
export GOPROXY=https://proxy.golang.org
export GOSUMDB=sum.golang.org
export PATH="$GOROOT/bin:$PATH"
ENV
} > "$ROOT/env.sh"
source "$ROOT/env.sh"
go version
printf 'Ready. Run: source %q\n' "$ROOT/env.sh"
